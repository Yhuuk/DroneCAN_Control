#include "spi.h"

/* 单次 HAL 发送的超时时间。屏幕只写不读，正常情况下会立即完成。 */
#define LCD_SPI_TIMEOUT_MS 100U

/**
 * @brief 通过 SPI1 阻塞发送一个字节。
 * @note  严格复刻原示例时序：每发送一个字节，CS 都产生一次完整的低脉冲。
 */
static void LCD_SPI_WriteByte(uint8_t data)
{
    HAL_GPIO_WritePin(OLED_CS_GPIO_Port, OLED_CS_Pin, GPIO_PIN_RESET);
    if (HAL_SPI_Transmit(&hspi1, &data, 1U, LCD_SPI_TIMEOUT_MS) != HAL_OK)
    {
        HAL_GPIO_WritePin(OLED_CS_GPIO_Port, OLED_CS_Pin, GPIO_PIN_SET);
        Error_Handler();
    }
    HAL_GPIO_WritePin(OLED_CS_GPIO_Port, OLED_CS_Pin, GPIO_PIN_SET);
}

void LCD_WriteDataBuffer(const uint8_t *data, uint16_t length)
{
    if ((data == NULL) || (length == 0U))
    {
        return;
    }

    /*
     * 显存数据允许在CS持续为低期间连续传输。与逐字节写法相比，这里只
     * 进入一次HAL发送循环并只切换一次CS，是刷新提速的关键。HAL不会
     * 修改发送缓冲区；强制转换仅用于兼容其未声明const的接口参数。
     */
    HAL_GPIO_WritePin(OLED_DC_GPIO_Port, OLED_DC_Pin, GPIO_PIN_SET);
    HAL_GPIO_WritePin(OLED_CS_GPIO_Port, OLED_CS_Pin, GPIO_PIN_RESET);
    if (HAL_SPI_Transmit(&hspi1,
                         (uint8_t *)data,
                         length,
                         LCD_SPI_TIMEOUT_MS) != HAL_OK)
    {
        HAL_GPIO_WritePin(OLED_CS_GPIO_Port, OLED_CS_Pin, GPIO_PIN_SET);
        Error_Handler();
    }
    HAL_GPIO_WritePin(OLED_CS_GPIO_Port, OLED_CS_Pin, GPIO_PIN_SET);
}

/** @brief 向屏幕写一个命令字节（DC=0）。 */
void LCD_WR_REG(uint8_t reg)
{
    HAL_GPIO_WritePin(OLED_DC_GPIO_Port, OLED_DC_Pin, GPIO_PIN_RESET);
    LCD_SPI_WriteByte(reg);

    /* 原示例在命令字节结束后将 DC 恢复为数据电平。 */
    HAL_GPIO_WritePin(OLED_DC_GPIO_Port, OLED_DC_Pin, GPIO_PIN_SET);
}

/** @brief 向屏幕写一个 8 位参数（DC=1）。 */
void LCD_WR_DATA8(uint8_t data)
{
    HAL_GPIO_WritePin(OLED_DC_GPIO_Port, OLED_DC_Pin, GPIO_PIN_SET);
    LCD_SPI_WriteByte(data);
}

/** @brief 向屏幕写一个 RGB565 像素，高字节先发送。 */
void LCD_WR_DATA(uint16_t data)
{
    const uint8_t pixel_bytes[2] = {
        (uint8_t)(data >> 8),
        (uint8_t)data
    };

    LCD_WriteDataBuffer(pixel_bytes, (uint16_t)sizeof(pixel_bytes));
}

/**
 * @brief 连续写入相同颜色，供区域填充使用。
 * @note  使用64像素的小缓冲区分块发送，不需要占用整屏帧缓冲区。
 */
static void LCD_WriteColorRepeat(uint16_t color, uint32_t count)
{
    uint8_t color_buffer[64U * 2U];

    for (uint16_t index = 0U; index < 64U; ++index)
    {
        color_buffer[index * 2U] = (uint8_t)(color >> 8);
        color_buffer[(index * 2U) + 1U] = (uint8_t)color;
    }

    while (count > 0U)
    {
        const uint16_t pixels_this_transfer =
            (count > 64U) ? 64U : (uint16_t)count;

        LCD_WriteDataBuffer(
            color_buffer,
            (uint16_t)(pixels_this_transfer * 2U));
        count -= pixels_this_transfer;
    }
}



/**
 * @brief       设置显示窗口
 * @param       xs:窗口列起始地址
 * @param       ys:坐标行起始地址
 * @param       xe:窗口列结束地址
 * @param       ye:坐标行结束地址
 * @retval      无
 * @note        由于IC限制;列地址参数必须为4的倍数
 */
void LCD_Address_Set(uint16_t xs, uint16_t ys, uint16_t xe, uint16_t ye)
{
    LCD_WR_REG(0x2A); // 列地址设置
    LCD_WR_DATA8(xs >> 8);
    LCD_WR_DATA8(xs & 0xFF);
    LCD_WR_DATA8(xe >> 8);
    LCD_WR_DATA8(xe & 0xFF);
    LCD_WR_REG(0x2B); // 行地址设置
    LCD_WR_DATA8(ys >> 8);
    LCD_WR_DATA8(ys & 0xFF);
    LCD_WR_DATA8(ye >> 8);
    LCD_WR_DATA8(ye & 0xFF);
    LCD_WR_REG(0x2c); // 储存器写
    HAL_Delay(5U);
    LCD_WR_REG(0x2c);
}

/**
 * @brief       指定颜色填充区域
 * @param       xs:填充区域列起始地址
 * @param       ys:填充区域行起始地址
 * @param       xe:填充区域列结束地址
 * @param       ye:填充区域行结束地址
 * @param       color:填充颜色值
 * @retval      无
 */
void LCD_Fill(uint16_t xs, uint16_t ys, uint16_t xe, uint16_t ye, uint16_t color)
{
    if ((xs >= xe) || (ys >= ye) || (xe > LCD_W) || (ye > LCD_H))
    {
        return;
    }

    LCD_Address_Set(xs, ys, xe - 1, ye - 1);
    LCD_WriteColorRepeat(color, (uint32_t)(xe - xs) * (uint32_t)(ye - ys));
}

